#!/usr/bin/python
"""Coverage of a TRANSP CDF by measured reads and by the mapping registry.

Unlike ``audit_mapping_coverage.py`` (a static string heuristic) this uses what the converter
actually read, taken from the ``*-conversion.json`` journals (``consumed`` per writer), and what
``mapping_registry.yaml`` states.  Every CDF variable falls in exactly one class:

* ``registered_typed``   registry entry of kind direct_typed / derived_typed / xml_only
* ``registered_input``   registry input_consumed (read to build or normalise other mappings)
* ``deferred``           registry deferred (reviewed, intentionally not exported)
* ``read_unregistered``  read by a writer but not in the registry: recognised, semantics not registered
* ``unknown``            not read and not registered

Three coverage figures are reported per case so none is mistaken for another:

* all-source:  read by any writer / all variables,
* applicable:  the same over variables that are numeric, time-dependent (TIME or TIME3 dimension)
               and not identically zero; defined by data properties only,
* registered typed exports: variables in typed/xml registry entries / applicable.

A variable being read is never counted as exported.
"""

import argparse
import json
import sys
from pathlib import Path

import numpy as np
from scipy.io import netcdf_file

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))
import mapping_registry as reg

CLASSES = ('registered_typed', 'registered_input', 'deferred', 'read_unregistered', 'unknown')
TIME_DIMENSIONS = ('TIME', 'TIME3')


def registry_class(entries, name):
    """Registry class of ``name`` (typed wins over input wins over deferred), or ``None``."""
    found = {e['kind'] for e in entries if reg.entry_matches_variable(e, name)}
    if found & {'direct_typed', 'derived_typed', 'xml_only'}:
        return 'registered_typed'
    if 'input_consumed' in found:
        return 'registered_input'
    if 'deferred' in found:
        return 'deferred'
    return None


def is_applicable(variable):
    if variable.data.dtype.kind not in 'fiu':
        return False
    if not any(dim in TIME_DIMENSIONS for dim in variable.dimensions):
        return False
    data = np.asarray(variable.data)
    return bool(np.any(np.isfinite(data) & (data != 0)))


def case_report(journal_path, entries):
    journal = json.loads(Path(journal_path).read_text(encoding='utf-8'))
    cdf = Path(journal['source_cdf'])
    if journal.get('status') != 'PASS' or not cdf.is_file():
        return None            # a failed or stale run says nothing reliable about what is read
    read = set(journal.get('setup_reads', ()))
    for writer in journal['writers']:
        read |= set(writer.get('consumed', ()))
    rows = {}
    with netcdf_file(str(cdf), 'r', mmap=True) as handle:
        for name, variable in handle.variables.items():
            cls = registry_class(entries, name)
            if cls is None:
                cls = 'read_unregistered' if name in read else 'unknown'
            rows[name] = {'class': cls, 'read': name in read, 'applicable': is_applicable(variable)}
    applicable = [n for n, r in rows.items() if r['applicable']]
    return {
        'case': journal_path.name.replace('-conversion.json', ''),
        'variables': len(rows),
        'by_class': {c: sum(r['class'] == c for r in rows.values()) for c in CLASSES},
        'read': sum(r['read'] for r in rows.values()),
        'applicable': len(applicable),
        'applicable_read': sum(rows[n]['read'] for n in applicable),
        'applicable_registered_typed': sum(rows[n]['class'] == 'registered_typed' for n in applicable),
        'applicable_unknown_unread': sorted(n for n in applicable if rows[n]['class'] == 'unknown'),
    }


def render(reports):
    lines = ['# Mapping coverage (measured reads and registry)', '',
             'Generated by `examples/report_coverage.py`.  "read" means a writer read the variable; it is not an export.', '',
             '| case | variables | read | applicable | applicable read | applicable in typed registry | typed | input | deferred | read, unregistered | unknown |',
             '|---|---|---|---|---|---|---|---|---|---|---|']
    for r in reports:
        c = r['by_class']
        lines.append(f'| {r["case"]} | {r["variables"]} | {r["read"]} | {r["applicable"]} | {r["applicable_read"]} | '
                     f'{r["applicable_registered_typed"]} | {c["registered_typed"]} | {c["registered_input"]} | '
                     f'{c["deferred"]} | {c["read_unregistered"]} | {c["unknown"]} |')
    return '\n'.join(lines) + '\n'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--journals', type=Path, default=ROOT / 'build' / 'end-to-end')
    parser.add_argument('--out-dir', type=Path, default=ROOT / 'build' / 'coverage')
    args = parser.parse_args(argv)
    entries = reg.load_registry()
    reports = [r for r in (case_report(p, entries) for p in sorted(args.journals.glob('*-conversion.json')))
               if r is not None]
    if not reports:
        print(f'no usable journals in {args.journals}; run make verify-end-to-end first')
        return 1
    args.out_dir.mkdir(parents=True, exist_ok=True)
    (args.out_dir / 'coverage.json').write_text(json.dumps(reports, indent=2, sort_keys=True) + '\n', encoding='utf-8')
    text = render(reports)
    (args.out_dir / 'coverage.md').write_text(text, encoding='utf-8')
    print(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
